<?php
/**
 * Protected storage for generated documents and cached remote assets.
 *
 * @package IDTA\PDF
 */

declare( strict_types=1 );

namespace IDTA\PDF;

defined( 'ABSPATH' ) || exit;

/**
 * Owns the plugin's directories under wp-content/uploads.
 */
final class Filesystem {

	/**
	 * Directory name inside the uploads folder.
	 */
	private const DIR_NAME = 'idta-pdf';

	/**
	 * Absolute path to the plugin's upload directory.
	 *
	 * @return string
	 */
	public function base_dir(): string {
		$uploads = wp_get_upload_dir();

		return trailingslashit( $uploads['basedir'] ) . self::DIR_NAME;
	}

	/**
	 * Documents directory for a given order.
	 *
	 * Documents are namespaced by order ID and a per-order token so that the
	 * path cannot be guessed from the order number alone.
	 *
	 * @param \WC_Order $order Order object.
	 *
	 * @return string
	 */
	public function order_dir( \WC_Order $order ): string {
		$dir = sprintf(
			'%s/documents/%s/%d-%s',
			$this->base_dir(),
			gmdate( 'Y/m', $this->order_timestamp( $order ) ),
			$order->get_id(),
			$this->order_token( $order )
		);

		$this->ensure_dir( $dir );

		return $dir;
	}

	/**
	 * Cache directory for localised remote assets.
	 *
	 * @return string
	 */
	public function cache_dir(): string {
		$dir = $this->base_dir() . '/cache';

		$this->ensure_dir( $dir );

		return $dir;
	}

	/**
	 * Temporary directory used by the PDF engine.
	 *
	 * @return string
	 */
	public function temp_dir(): string {
		$dir = $this->base_dir() . '/tmp';

		$this->ensure_dir( $dir );

		return $dir;
	}

	/**
	 * Stable per-order token, generated once and stored on the order.
	 *
	 * @param \WC_Order $order Order object.
	 *
	 * @return string
	 */
	public function order_token( \WC_Order $order ): string {
		$token = $order->get_meta( '_idta_pdf_token', true );

		if ( is_string( $token ) && 1 === preg_match( '/^[a-f0-9]{16}$/', $token ) ) {
			return $token;
		}

		$token = substr( bin2hex( random_bytes( 8 ) ), 0, 16 );

		$order->update_meta_data( '_idta_pdf_token', $token );
		$order->save_meta_data();

		return $token;
	}

	/**
	 * Create the base directory and its guards.
	 */
	public function ensure_base_dir(): void {
		$this->ensure_dir( $this->base_dir() );
	}

	/**
	 * Create a directory, with web access denied.
	 *
	 * @param string $dir Absolute path.
	 *
	 * @return bool Whether the directory exists and is writable.
	 */
	public function ensure_dir( string $dir ): bool {
		if ( ! wp_mkdir_p( $dir ) ) {
			return false;
		}

		$this->protect( $this->base_dir() );

		return wp_is_writable( $dir );
	}

	/**
	 * Write directory-listing and direct-access guards.
	 *
	 * Apache honours .htaccess; nginx and LiteSpeed do not, which is why
	 * downloads are always served through the download handler rather than by
	 * linking to these files.
	 *
	 * @param string $dir Absolute path.
	 */
	private function protect( string $dir ): void {
		$htaccess = $dir . '/.htaccess';

		if ( ! file_exists( $htaccess ) ) {
			$rules = "# Generated by IDTA PDF. Do not edit.\n"
				. "<IfModule mod_authz_core.c>\n\tRequire all denied\n</IfModule>\n"
				. "<IfModule !mod_authz_core.c>\n\tOrder allow,deny\n\tDeny from all\n</IfModule>\n";

			$this->put_contents( $htaccess, $rules );
		}

		$index = $dir . '/index.php';

		if ( ! file_exists( $index ) ) {
			$this->put_contents( $index, "<?php\n// Silence is golden.\n" );
		}
	}

	/**
	 * Write a file through WP_Filesystem, falling back to a direct write.
	 *
	 * @param string $file     Absolute path.
	 * @param string $contents File contents.
	 *
	 * @return bool
	 */
	public function put_contents( string $file, string $contents ): bool {
		global $wp_filesystem;

		if ( ! $wp_filesystem instanceof \WP_Filesystem_Base ) {
			$bootstrap = ABSPATH . 'wp-admin/includes/file.php';

			// Front-end and cron requests do not load the admin file API.
			if ( ! function_exists( 'WP_Filesystem' ) && is_readable( $bootstrap ) ) {
				require_once $bootstrap;
			}

			if ( function_exists( 'WP_Filesystem' ) ) {
				WP_Filesystem();
			}
		}

		if ( $wp_filesystem instanceof \WP_Filesystem_Base ) {
			return (bool) $wp_filesystem->put_contents( $file, $contents, FS_CHMOD_FILE );
		}

		// Direct write fallback, used when WP_Filesystem is unavailable.
		// phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents
		return false !== file_put_contents( $file, $contents, LOCK_EX );
	}

	/**
	 * Delete a file if it sits inside the plugin's storage.
	 *
	 * @param string $file Absolute path.
	 *
	 * @return bool
	 */
	public function delete( string $file ): bool {
		if ( '' === $file || ! $this->is_managed( $file ) || ! file_exists( $file ) ) {
			return false;
		}

		// wp_delete_file() returns void; report on the file's absence instead.
		wp_delete_file( $file );

		return ! file_exists( $file );
	}

	/**
	 * Whether a path lives inside the plugin's storage directory.
	 *
	 * Guards the download handler and delete routines against traversal.
	 *
	 * @param string $file Absolute path.
	 *
	 * @return bool
	 */
	public function is_managed( string $file ): bool {
		if ( '' === $file ) {
			return false;
		}

		$base = wp_normalize_path( $this->base_dir() );

		// Prefer realpath, which also resolves symlinks. It returns false for
		// paths that do not exist yet, so fall back to collapsing the path
		// lexically — otherwise unresolved ../ segments would pass the prefix
		// check below.
		$resolved = realpath( $file );

		$real = false !== $resolved
			? wp_normalize_path( $resolved )
			: $this->collapse_path( wp_normalize_path( $file ) );

		return str_starts_with( $real, trailingslashit( $base ) );
	}

	/**
	 * Collapse "." and ".." segments in a path without touching the filesystem.
	 *
	 * @param string $path Normalised path.
	 *
	 * @return string
	 */
	private function collapse_path( string $path ): string {
		$absolute = str_starts_with( $path, '/' );
		$out      = array();

		foreach ( explode( '/', $path ) as $segment ) {
			if ( '' === $segment || '.' === $segment ) {
				continue;
			}

			if ( '..' === $segment ) {
				array_pop( $out );

				continue;
			}

			$out[] = $segment;
		}

		return ( $absolute ? '/' : '' ) . implode( '/', $out );
	}

	/**
	 * Remove cached assets older than a day.
	 */
	public function purge_cache(): void {
		$dir = $this->cache_dir();

		$files = glob( $dir . '/*' );

		if ( ! is_array( $files ) ) {
			return;
		}

		$cutoff = time() - DAY_IN_SECONDS;

		foreach ( $files as $file ) {
			if ( ! is_file( $file ) || str_ends_with( $file, '.htaccess' ) || str_ends_with( $file, 'index.php' ) ) {
				continue;
			}

			$modified = filemtime( $file );

			if ( false !== $modified && $modified < $cutoff ) {
				wp_delete_file( $file );
			}
		}
	}

	/**
	 * Order creation timestamp, falling back to now.
	 *
	 * @param \WC_Order $order Order object.
	 *
	 * @return int
	 */
	private function order_timestamp( \WC_Order $order ): int {
		$created = $order->get_date_created();

		return $created instanceof \WC_DateTime ? $created->getTimestamp() : time();
	}
}
